-- ==============================================================================
-- NORTHSTAR FACILITY SERVICES — PHASE 2D: SECURE PUBLIC LEAD SUBMISSION RPC
-- ==============================================================================
-- Target Database: Supabase / PostgreSQL (northstar-facility-services)
-- Purpose: Provide a dedicated, narrowly scoped, security-definer RPC for public
--          commercial service inquiries submitted via the public contact form (/contact).
--
-- Security Architecture:
--   - Solves the '42501 permission denied' barrier for anonymous public visitors
--     without granting SELECT privileges on public.leads, commercial_properties,
--     or profiles to anon.
--   - Returns ONLY the generated business tracking code (lead_code, e.g. 'LEAD-1083')
--     required for the customer confirmation receipt.
--   - Exposes zero lead records, zero sensitive contact details, and zero internal IDs.
--   - Rejects any caller attempt to set assigned technician, property relationship,
--     estimated value, facility square footage, custom status, or priority.
--   - Database defaults remain authoritative for lead_code (via lead_code_seq),
--     status ('new'), priority ('standard'), and timestamps.
--   - Defensively configured: SECURITY DEFINER with fixed search_path = public, pg_temp.
--   - Strict input validation prevents insertion of blank or malformed inquiries.
--
-- Execution Rule: Transaction-safe (BEGIN ... COMMIT) and idempotent.
-- ==============================================================================

BEGIN;

-- ------------------------------------------------------------------------------
-- 1. SECURE PUBLIC LEAD SUBMISSION FUNCTION
-- ------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.submit_public_inquiry(
  p_name TEXT,
  p_email TEXT,
  p_company TEXT,
  p_phone TEXT,
  p_service_needed TEXT,
  p_property_type TEXT,
  p_property_address TEXT,
  p_message TEXT DEFAULT '',
  p_preferred_contact_method TEXT DEFAULT 'phone'
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_clean_name TEXT;
  v_clean_email TEXT;
  v_clean_company TEXT;
  v_clean_phone TEXT;
  v_clean_service TEXT;
  v_clean_prop_type TEXT;
  v_clean_address TEXT;
  v_clean_message TEXT;
  v_clean_contact_method TEXT;
  v_lead_code TEXT;
BEGIN
  -- 1. Sanitize and normalize input parameters
  v_clean_name := trim(COALESCE(p_name, ''));
  v_clean_email := trim(COALESCE(p_email, ''));
  v_clean_company := trim(COALESCE(p_company, ''));
  v_clean_phone := trim(COALESCE(p_phone, ''));
  v_clean_service := trim(COALESCE(p_service_needed, ''));
  v_clean_prop_type := trim(COALESCE(p_property_type, ''));
  v_clean_address := trim(COALESCE(p_property_address, ''));
  v_clean_message := trim(COALESCE(p_message, ''));
  v_clean_contact_method := lower(trim(COALESCE(p_preferred_contact_method, 'phone')));

  -- 2. Server-side validation consistent with the public contact form
  IF v_clean_name = '' THEN
    RAISE EXCEPTION 'Full name is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_email = '' OR v_clean_email NOT LIKE '%@%.%' THEN
    RAISE EXCEPTION 'Valid business email is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_company = '' THEN
    RAISE EXCEPTION 'Company or facility name is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_phone = '' THEN
    RAISE EXCEPTION 'Contact phone number is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_service = '' THEN
    RAISE EXCEPTION 'Primary facility discipline is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_prop_type = '' THEN
    RAISE EXCEPTION 'Commercial property environment is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_address = '' THEN
    RAISE EXCEPTION 'Property address or location is required.' USING ERRCODE = '22023';
  END IF;

  IF v_clean_contact_method NOT IN ('phone', 'email', 'either') THEN
    RAISE EXCEPTION 'Preferred contact method must be phone, email, or either.' USING ERRCODE = '22023';
  END IF;

  -- 3. Execute INSERT into public.leads
  -- Note: lead_code, status ('new'), priority ('standard'), created_at, and updated_at
  -- are automatically generated by PostgreSQL table defaults.
  -- assigned_technician_id, property_id, and estimated_value explicitly remain NULL.
  INSERT INTO public.leads (
    name,
    email,
    company,
    phone,
    service_needed,
    property_type,
    property_address,
    message,
    preferred_contact_method
  ) VALUES (
    v_clean_name,
    v_clean_email,
    v_clean_company,
    v_clean_phone,
    v_clean_service,
    v_clean_prop_type,
    v_clean_address,
    v_clean_message,
    v_clean_contact_method
  )
  RETURNING lead_code INTO v_lead_code;

  -- 4. Return ONLY the business tracking identifier for receipt confirmation
  RETURN v_lead_code;
END;
$$;

-- ------------------------------------------------------------------------------
-- 2. FUNCTION PRIVILEGES & SECURITY HARDENING
-- ------------------------------------------------------------------------------

-- Revoke default public execution privilege
REVOKE ALL ON FUNCTION public.submit_public_inquiry(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) FROM PUBLIC;

-- Grant EXECUTE strictly to anon (for public web inquiries) and authenticated (for testing/staff)
GRANT EXECUTE ON FUNCTION public.submit_public_inquiry(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) TO anon, authenticated;

COMMIT;

